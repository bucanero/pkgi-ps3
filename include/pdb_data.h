// multi-pkg xml data
// 0x00   ID | size
// 0x00001388 string -> url (split part 1/x)
// 0x00001389 string -> complete file name
// 0x0000138A 08/08 -> part size (8 bytes)
// 0x0000138D 04/04 -> unknown (4 bytes) 25 EE 0C BF
// 0x0000138E 20/20 -> hash? (20 bytes)

// 0x13A8 string -> url (split part 2/x)
// 0x13A9 string -> complete file name
// 0x13AA 08/08 -> part size (8 bytes)
// 0x13AD 04/04 -> unknown (4 bytes) 25 EE 0E 73
// 0x13AE 20/20 -> hash? (20 bytes)

// 0x13C8 string -> url (split part 3/x)
// 0x13C9 string -> complete file name
// 0x13CA 08/08 -> part size (8 bytes)
// 0x13CD 04/04 -> unknown (4 bytes) 25 EE 0F 7E
// 0x13CE 20/20 -> hash? (20 bytes)

// 0x13E8 string -> url (split part 4/x)
// 0x13E9 string -> complete file name
// 0x13EA 08/08 -> part size (8 bytes)
// 0x13ED 04/04 -> unknown (4 bytes) 25 EE 10 80
// 0x13EE 20/20 -> hash? (20 bytes)

// 0x1408 string -> url (split part 5/x)
// 0x1409 string -> complete file name
// 0x140A 08/08 -> part size (8 bytes)
// 0x140D 04/04 -> unknown (4 bytes) 25 EE 11 81
// 0x140E 20/20 -> hash? (20 bytes)

// 0x1428 string -> url (split part 6/x)
// 0x1429 string -> complete file name
// 0x142A 08/08 -> part size (8 bytes)
// 0x142D 04/04 -> unknown (4 bytes) 25 EE 12 7C
// 0x142E 20/20 -> hash? (20 bytes)

// 0x1448 string -> url (split part 7/x)
// 0x1449 string -> complete file name
// 0x144A 08/08 -> part size (8 bytes)
// 0x144D 04/04 -> unknown (4 bytes) 25 EE 13 79
// 0x144E 20/20 -> hash? (20 bytes)

// 0x000000D0 08/08 -> total downloaded size (8 bytes)
// 0x000000CE 08/08 -> total expected part size (8 bytes)

// 0x000000FB 08/08 -> 0 unknown (8 bytes)
// 0x000000E6 04/04 -> 0 unknown (4 bytes)
// 0x000000E5 04/04 -> 7 total parts? (4 bytes)
// 0x000000FA 08/08 -> pdb total pkg size (8 bytes)
// 0x000000CB string -> complete pkg file name
// 0x000000CC string -> date/time
// 0x000000CA string -> download URL (first part URL)
// 0x0000006A string -> icon location/path
// 0x00000069 string -> display title
// 0x000000D9 string -> content id
// ... 0xf0 0xf1 0xf4 0xda 0xcd 0xec 0xfc

